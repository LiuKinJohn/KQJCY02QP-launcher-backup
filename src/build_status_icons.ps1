$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore,WindowsBase

# The 24x16 marks are drawn for this status bar. Curves are symmetric about
# x=12 and share the same 1.8 px stroke. The percentage is set separately.
$width = 24
$height = 16
$ink = [Windows.Media.Brushes]::White

function New-Pen([double]$thickness) {
    $p = [Windows.Media.Pen]::new($ink, $thickness)
    $p.StartLineCap = [Windows.Media.PenLineCap]::Round
    $p.EndLineCap = [Windows.Media.PenLineCap]::Round
    $p.LineJoin = [Windows.Media.PenLineJoin]::Round
    $p.Freeze()
    return $p
}

function Add-Wifi($dc, [bool]$offline) {
    $pen = New-Pen 1.8
    $arcs = @(
        'M 2,6.0 C 7.5,1.1 16.5,1.1 22,6.0',
        'M 5.6,9.2 C 9.2,5.9 14.8,5.9 18.4,9.2'
    )
    if (!$offline) { $arcs += 'M 9.3,12.3 C 10.8,10.9 13.2,10.9 14.7,12.3' }
    foreach ($d in $arcs) {
        $dc.DrawGeometry($null, $pen, [Windows.Media.Geometry]::Parse($d))
    }
    if ($offline) {
        $dc.DrawGeometry($null, (New-Pen 1.65),
            [Windows.Media.Geometry]::Parse('M 10.4,11.0 L 13.6,14.5 M 13.6,11.0 L 10.4,14.5'))
    } else {
        $dc.DrawEllipse($ink, $null, [Windows.Point]::new(12,14.2), 1.05, 1.05)
    }
}

function Add-Battery($dc, [string]$part) {
    $outline = New-Pen 1.65
    if ($part -eq 'shell' -or $part -eq 'charging' -or $part -eq 'external') {
        $dc.DrawRoundedRectangle($null, $outline,
            [Windows.Rect]::new(1.25,3.25,19,9.5), 2.5, 2.5)
        $dc.DrawRoundedRectangle($ink, $null,
            [Windows.Rect]::new(21.1,6.0,1.8,4.0), 0.8, 0.8)
    }
    if ($part -eq 'full' -or $part -eq 'high' -or $part -eq 'mid' -or $part -eq 'low') {
        $end = switch ($part) { full { 18.2 } high { 17.5 } mid { 11.8 } low { 6.1 } }
        $dc.DrawRoundedRectangle($ink, $null,
            [Windows.Rect]::new(3.8,5.8,$end - 3.8,4.4), 0.8, 0.8)
    }
    if ($part -eq 'charging') {
        $dc.DrawGeometry($ink, $null, [Windows.Media.Geometry]::Parse(
            'M 13.2,4.7 L 8.9,8.8 L 11.4,8.8 L 10.6,11.6 L 15.2,7.2 L 12.7,7.2 Z'))
    }
    if ($part -eq 'external') {
        $dc.DrawGeometry($null, (New-Pen 1.45), [Windows.Media.Geometry]::Parse(
            'M 9.3,5.1 L 9.3,7.2 M 13.5,5.1 L 13.5,7.2 M 8.6,7.2 L 14.2,7.2 L 14.2,8.9 C 14.2,10.1 13.2,10.7 11.4,10.7 L 11.4,11.8'))
    }
}

function Add-Power($dc, [string]$part) {
    if ($part -eq 'charging') {
        $dc.DrawGeometry($ink, $null, [Windows.Media.Geometry]::Parse(
            'M 13.4,1.2 L 6.6,9.1 L 10.8,9.1 L 9.6,14.9 L 17.4,6.4 L 13.1,6.4 Z'))
    } elseif ($part -eq 'plug') {
        $pen = New-Pen 1.8
        $dc.DrawGeometry($null, $pen, [Windows.Media.Geometry]::Parse(
            'M 8.4,1.7 L 8.4,5.1 M 15.6,1.7 L 15.6,5.1 M 6.7,5.2 L 17.3,5.2 L 17.3,8.5 C 17.3,11.1 15.1,12.7 12,12.7 C 8.9,12.7 6.7,11.1 6.7,8.5 Z M 12,12.7 L 12,15'))
    }
}

function Get-Mask([string]$name) {
    $visual = [Windows.Media.DrawingVisual]::new()
    $dc = $visual.RenderOpen()
    if ($name.StartsWith('wifi_')) { Add-Wifi $dc ($name -eq 'wifi_off') }
    elseif ($name.StartsWith('power_')) { Add-Power $dc $name.Substring(6) }
    else { Add-Battery $dc $name.Substring(8) }
    $dc.Close()
    $bitmap = [Windows.Media.Imaging.RenderTargetBitmap]::new(
        $width, $height, 96, 96, [Windows.Media.PixelFormats]::Pbgra32)
    $bitmap.Render($visual)
    $pixels = [byte[]]::new($width * $height * 4)
    $bitmap.CopyPixels($pixels, $width * 4, 0)
    $mask = [byte[]]::new($width * $height)
    for ($i = 0; $i -lt $mask.Length; $i++) { $mask[$i] = $pixels[$i * 4 + 3] }
    return ,$mask
}

$lines = [Collections.Generic.List[string]]::new()
$lines.Add('/* 24x16 Launcher status marks; generated by build_status_icons.ps1. */')
$lines.Add('#ifndef STATUS_ICONS_H')
$lines.Add('#define STATUS_ICONS_H')
foreach ($name in @('wifi_on','wifi_off','power_plug','power_charging','battery_shell','battery_full','battery_high','battery_mid','battery_low','battery_charging','battery_external')) {
    $mask = Get-Mask $name
    $lines.Add("static const uint8_t status_$name[384] = {")
    for ($y = 0; $y -lt $height; $y++) {
        $row = $mask[($y * $width)..($y * $width + $width - 1)] | ForEach-Object { $_.ToString().PadLeft(3) }
        $lines.Add('    ' + ($row -join ', ') + ',')
    }
    $lines.Add('};')
}
$lines.Add('#endif')
Set-Content (Join-Path $PSScriptRoot 'status_icons.h') $lines -Encoding utf8
