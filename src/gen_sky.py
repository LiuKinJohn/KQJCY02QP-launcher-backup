# -*- coding: utf-8 -*-
"""Sample the 16 macOS 'Solar Gradients' wallpapers into a 13-stop vertical
palette per frame and emit a C header for the launcher."""
import glob
import io
import os

from PIL import Image

SRC = r'E:\Wallpaper\macOS 26 Tahoe All Wallpapers\heic转jpg\daily'
B = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(B, 'sky_stops.h')
N = 13

files = sorted(glob.glob(os.path.join(SRC, '*.jpg')),
               key=lambda f: int(''.join(c for c in os.path.basename(f) if c.isdigit()) or 0))
assert len(files) == 16, len(files)

STOPS = tuple(0.02 + 0.96 * i / (N - 1) for i in range(N))
rows = []
for f in files:
    im = Image.open(f).convert('RGB')
    w, h = im.size
    cols = []
    for fy in STOPS:
        y = max(0, min(h - 1, int(h * fy)))
        acc = [0, 0, 0]
        n = 0
        for x in range(0, w, max(1, w // 64)):
            p = im.getpixel((x, y))
            acc[0] += p[0]
            acc[1] += p[1]
            acc[2] += p[2]
            n += 1
        cols.append('%06X' % (acc[0] // n << 16 | acc[1] // n << 8 | acc[2] // n))
    rows.append(cols)

with io.open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('/* generated by gen_sky.py - 16 solar-gradient frames, %d stops each */\n' % N)
    f.write('#define SKY_N %d\n' % N)
    f.write('static const uint32_t SKY_STOPS[16][SKY_N] = {\n')
    for i, cols in enumerate(rows):
        f.write('    { %s },  /* %d */\n' % (', '.join('0x' + c for c in cols), i + 1))
    f.write('};\n')

print('sky_stops.h written, %d frames x %d stops' % (len(rows), N))
